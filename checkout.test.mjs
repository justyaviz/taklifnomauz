 proc=spawn(process.execPath,['server.mjs'],{env:{...process.env,PORT:String(port),DATA_DIR:temp,NODE_ENV:'test',ADMIN_USERNAME:'admin',ADMIN_PASSWORD_HASH:salt+':'+scryptSync(password,salt,64).toString('hex'),ADMIN_SESSION_SECRET:randomBytes(50).toString('hex'),TELEGRAM_BOT_TOKEN:'',TELEGRAM_WEBHOOK_SECRET:''},stdio:'ignore'});
 let running=false;
