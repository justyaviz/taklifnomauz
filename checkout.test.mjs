test('admin card receiver and prices enable standalone payment order',async()=>{
 let r=await auth('/api/admin/card/settings','PUT',{cardNumber:'8600 1111 2222 3333',cardHolder:'TOHIRBEK TESTOV',prices:{'oq-saroy':250000,zarhal:300000,minimal:150000}});
 assert.equal(r.status,200);
 r=await request('/api/checkout/payment-details');const d=await r.json();assert.equal(d.configured,true);assert.equal(d.cardHolder,'TOHIRBEK TESTOV');
 assert.equal(d.cardNumber,'8600111122223333');
 r=await request('/api/checkout/orders','POST',{template:'zarhal',customerName:'Ali Valiyev',contact:'@alivali'});
 assert.equal(r.status,201);
 const o=await r.json();orderId=o.orderId;orderToken=o.accessToken;
 assert.equal(o.amount,300000);assert.equal(o.status,'awaiting_receipt');
 assert.equal((await request('/api/checkout/orders/'+orderId)).status,404);
 r=await request('/api/checkout/orders/'+orderId,'GET',null,{'X-Order-Token':orderToken});assert.equal(r.status,200);
 const detail=await r.json();assert.equal(detail.claimCode,null);assert.equal(detail.customerName,'Ali Valiyev');
 assert.equal((await auth('/api/admin/card/receipts/'+orderId)).status,404);
});
test('receipt is private, requires verification, then issues activation code',async()=>{
 const bytes=Buffer.concat([Buffer.from('89504e470d0a1a0a','hex'),randomBytes(480)]);
 let r=await request('/api/checkout/orders/'+orderId+'/receipt','POST',bytes,{'X-Order-Token':orderToken,'Content-Type':'image/png'});
 assert.equal(r.status,200);
 assert.equal((await r.json()).status,'review');
 assert.equal((await request('/api/admin/card/receipts/'+orderId)).status,401);
 r=await auth('/api/admin/card/receipts/'+orderId);assert.equal(r.status,200);assert.equal(r.headers.get('content-type'),'image/png');
 assert.equal(Buffer.from(await r.arrayBuffer()).length,bytes.length);
 const blocked=await request('/api/checkout/orders/'+orderId,'GET',null,{'X-Order-Token':orderToken});
 assert.equal((await blocked.json()).claimCode,null);
 r=await auth('/api/admin/card/orders/'+orderId,'PATCH',{status:'approved'});assert.equal(r.status,200);
 r=await request('/api/checkout/orders/'+orderId,'GET',null,{'X-Order-Token':orderToken});
 const st=await r.json();assert.equal(st.status,'approved');assert.match(st.claimCode,/^TKF-[A-F0-9]{24}$/);claimCode=st.claimCode;
 assert.equal((await auth('/api/admin/card/orders/'+orderId,'PATCH',{status:'approved'})).status,409);
});
